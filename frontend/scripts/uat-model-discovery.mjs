import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { createServer } from 'node:http';
import { fileURLToPath } from 'node:url';
import { resolveBrowserExecutable } from './browser-executable.mjs';
const require = createRequire(new URL('../package.json', import.meta.url));
const { chromium } = require('playwright-core');
const { default: AxeBuilder } = await import('@axe-core/playwright');
const repository = fileURLToPath(new URL('../../', import.meta.url));
await mkdir(join(repository, '.cache'), { recursive: true });
const root = await mkdtemp(join(repository, '.cache/discovery-uat-'));
process.env.PI_SCIENCE_HOME = join(root, 'state');
process.env.PI_SCIENCE_WORKSPACES = join(root, 'workspaces');
process.env.PI_SCIENCE_FRONTEND_DIST = join(repository, 'frontend/dist');
process.env.PI_SCIENCE_INTERNAL_TOKEN = 'local-discovery-uat-token';
process.env.PI_SCIENCE_AI_TITLES = '0';
process.env.LOG_LEVEL = 'silent';
await mkdir(process.env.PI_SCIENCE_WORKSPACES, { recursive: true });
await mkdir(process.env.PI_SCIENCE_HOME, { recursive: true });
const { buildApp } = await import('../../apps/server/dist/app/app.js');
const { loadConfig } = await import('../../apps/server/dist/config/config.js');
const { ModelRegistryService } = await import('../../apps/server/dist/model-config/model-registry-service.js');
const app = buildApp({ ...loadConfig(), port: 0 });
const requests = [];
let contextWindow = 8192;
const upstream = createServer(async (request, response) => {
  requests.push({ method: request.method, headers: request.headers });
  if (request.method === 'GET') {
    response.writeHead(200, { 'Content-Type': 'application/json' });
    response.end(JSON.stringify({ data: [{ id: 'chat-model', model_type: 'chat', context_length: contextWindow, max_output_tokens: 4096 }, { id: 'embedding-model', model_type: 'embedding' }] })); return;
  }
  for await (const _chunk of request) { /* consume streamed request */ }
  response.writeHead(200, { 'Content-Type': 'text/event-stream' });
  response.write(`data: ${JSON.stringify({ id: 'r', object: 'chat.completion.chunk', model: 'chat-model', choices: [{ index: 0, delta: { role: 'assistant', content: 'ok' }, finish_reason: null }] })}\n\n`);
  response.write(`data: ${JSON.stringify({ id: 'r', object: 'chat.completion.chunk', model: 'chat-model', choices: [{ index: 0, delta: {}, finish_reason: 'stop' }] })}\n\n`);
  response.end('data: [DONE]\n\n');
});
let browser;
try {
  await new Promise((resolve) => upstream.listen(0, '127.0.0.1', resolve));
  const modelUrl = `http://127.0.0.1:${upstream.address().port}/v1`;
  const origin = await app.listen({ host: '127.0.0.1', port: 0 });
  const api = async (path) => {
    const response = await fetch(origin + path, { headers: { 'x-pi-science-internal-token': process.env.PI_SCIENCE_INTERNAL_TOKEN } });
    assert.equal(response.status, 200); return response.json();
  };
  browser = await chromium.launch({ executablePath: await resolveBrowserExecutable(), headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ locale: 'en-US', viewport: { width: 1280, height: 900 }, extraHTTPHeaders: { 'x-pi-science-internal-token': process.env.PI_SCIENCE_INTERNAL_TOKEN } });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  await page.addInitScript(() => localStorage.setItem('pi-science.locale', JSON.stringify('en')));
  await page.goto(origin + '/settings');
  await page.getByRole('tab', { name: 'AI Models', exact: true }).click();
  await page.getByRole('button', { name: 'Connect a service', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Connect model service', exact: true });
  await dialog.getByRole('button', { name: 'Custom API', exact: true }).click();
  await dialog.getByLabel('Provider name', { exact: true }).fill('Discovery UAT');
  await dialog.getByLabel(/Base URL/).fill(modelUrl);
  await dialog.getByLabel('API key', { exact: true }).fill('draft-only-key');
  await page.waitForTimeout(1000);
  assert.equal(requests.length, 0, 'typing must not transmit credentials');
  await dialog.getByRole('button', { name: /^Credential source:/ }).click();
  await page.getByRole('menuitemradio', { name: 'Keyless', exact: true }).click();
  await dialog.getByRole('button', { name: 'Test connection and discover', exact: true }).click();
  const chat = dialog.getByRole('checkbox', { name: /chat-model/ });
  await chat.waitFor();
  assert.equal(await chat.isChecked(), true);
  assert.equal(await dialog.getByRole('checkbox', { name: /embedding-model/ }).isChecked(), false);
  assert.equal(requests.length, 1);
  assert.equal(requests[0].headers.authorization, undefined);
  await page.setViewportSize({ width: 375, height: 667 });
  assert.equal(await dialog.evaluate((node) => node.scrollWidth > node.clientWidth + 1), false, 'mobile discovery must not overflow');
  const accessibility = await new AxeBuilder({ page }).include('[role="dialog"]').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  assert.deepEqual(accessibility.violations.map(({ id }) => id), []);
  await page.setViewportSize({ width: 1280, height: 900 });

  await dialog.getByLabel('chat-model Context', { exact: true }).fill('128000');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  let snapshot = await api('/api/model-config');
  const id = Object.keys(snapshot.config.providers)[0];
  assert.equal(snapshot.config.providers[id].models[0].contextWindow, 8192);
  assert.equal(snapshot.config.providers[id].modelOverrides['chat-model'].contextWindow, 128000);
  assert.equal(snapshot.config.providers[id].models.length, 1);
  console.log('PASS explicit discovery, model type selection and separate persistent corrections');
  await page.getByRole('button', { name: 'Refresh models', exact: true }).click();
  await page.getByText('Model list refreshed.', { exact: true }).waitFor();
  assert.equal((await api('/api/model-config')).revision, snapshot.revision);
  contextWindow = 16000;
  await page.getByRole('button', { name: 'Refresh models', exact: true }).click();
  await page.getByText(/Refreshed · 0 added · 1 updated/).waitFor();
  snapshot = await api('/api/model-config');
  assert.equal(snapshot.config.providers[id].models[0].contextWindow, 16000);
  assert.equal(snapshot.config.providers[id].modelOverrides['chat-model'].contextWindow, 128000);
  const catalog = await api('/api/model-config/catalog');
  const effective = catalog.providers.find((provider) => provider.id === id).models[0];
  assert.equal(effective.contextWindow, 128000);
  assert.equal(effective.capability_sources.contextWindow, 'user_override');
  console.log('PASS unchanged refresh preserves revision; changed declaration preserves the override');
  await page.reload();
  await page.getByRole('tab', { name: 'AI Models', exact: true }).click();
  await page.getByRole('button', { name: 'Discovery UAT actions', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Edit connection', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'Discovery UAT · Edit connection', exact: true });
  await edit.getByRole('button', { name: 'Test connection and discover', exact: true }).click();
  await edit.getByLabel('chat-model Context', { exact: true }).waitFor();
  assert.equal(await edit.getByLabel('chat-model Context', { exact: true }).inputValue(), '128000');
  await edit.getByRole('button', { name: 'chat-model Use provider values', exact: true }).click();
  await edit.getByRole('button', { name: 'Save', exact: true }).click();
  await edit.waitFor({ state: 'hidden' });
  assert.equal((await api('/api/model-config/catalog')).providers.find((provider) => provider.id === id).models[0].contextWindow, 16000);
  const registry = new ModelRegistryService().compile();
  const result = await registry.streamSimple(registry.getModel(id, 'chat-model'), { messages: [{ role: 'user', content: 'hello', timestamp: 1 }] }).result();
  assert.equal(result.stopReason, 'stop');
  assert.ok(result.content.some((block) => block.type === 'text' && block.text === 'ok'));
  assert.equal(requests.at(-1).headers.authorization, undefined);
  assert.equal(requests.at(-1).headers['x-api-key'], undefined);
  console.log('PASS reopen, reset to provider values and real keyless streaming inference');
} finally {
  await browser?.close(); await app.close(); upstream.closeAllConnections();
  await new Promise((resolve) => upstream.close(resolve)); await rm(root, { recursive: true, force: true });
}
