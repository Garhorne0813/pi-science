import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { resolveBrowserExecutable } from './browser-executable.mjs';
const require = createRequire(new URL('../package.json', import.meta.url));
const { chromium } = require('playwright-core');
const repository = fileURLToPath(new URL('../../', import.meta.url));
await mkdir(join(repository, '.cache'), { recursive: true });
const root = await mkdtemp(join(repository, '.cache/native-model-uat-'));
process.env.PI_SCIENCE_HOME = join(root, 'state');
process.env.PI_SCIENCE_WORKSPACES = join(root, 'workspaces');
process.env.PI_SCIENCE_FRONTEND_DIST = join(repository, 'frontend/dist');
process.env.PI_SCIENCE_INTERNAL_TOKEN = 'local-model-uat-token';
process.env.PI_SCIENCE_MODEL_CONFIG_BACKEND = 'pi_ai_v1';
process.env.PI_SCIENCE_AI_TITLES = '0';
process.env.LAB_UAT_MODEL_KEY = 'local-uat-key-never-render';
await mkdir(process.env.PI_SCIENCE_WORKSPACES, { recursive: true });
const { buildApp } = await import('../../apps/server/dist/app/app.js');
const { loadConfig } = await import('../../apps/server/dist/config/config.js');
const app = buildApp({ ...loadConfig(), port: 0 });
let browser;
try {
  const origin = await app.listen({ host: '127.0.0.1', port: 0 });
  const api = async (path, method = 'GET', body) => {
    const response = await fetch(origin + path, { method, headers: { 'x-pi-science-internal-token': process.env.PI_SCIENCE_INTERNAL_TOKEN, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
    if (!response.ok) throw new Error(`${path}: ${response.status}`);
    return response.json();
  };
  browser = await chromium.launch({ executablePath: await resolveBrowserExecutable(), headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ locale: 'en-US', viewport: { width: 1280, height: 900 }, extraHTTPHeaders: { 'x-pi-science-internal-token': process.env.PI_SCIENCE_INTERNAL_TOKEN } });
  const page = await context.newPage();
  await page.addInitScript(() => { localStorage.setItem('pi-science.locale', JSON.stringify('en')); });
  await page.goto(origin + '/settings');
  await page.getByRole('tab', { name: 'AI Models', exact: true }).click();
  await page.getByRole('button', { name: 'Advanced model configuration', exact: true }).waitFor();
  await page.getByRole('button', { name: '+ Connect', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '+ Connect', exact: true });
  await dialog.getByLabel('Provider name', { exact: true }).fill('UAT Lab');
  await dialog.getByLabel('Provider ID', { exact: true }).fill('uat-lab');
  await dialog.getByLabel(/Base URL/).fill('http://127.0.0.1:9999/v1');
  await dialog.getByLabel('Keyless', { exact: true }).check();
  await dialog.getByLabel(/Manual model IDs/).fill('uat-model');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  const config = await api('/api/model-config');
  if (!config.config.providers['uat-lab'] || config.revision !== 1) throw new Error('Provider was not atomically committed');
  const search = page.getByRole('textbox', { name: /Search/ });
  await search.fill('UAT Lab');
  await page.getByRole('button', { name: 'UAT Lab', exact: true }).click();
  await page.getByText('Selectable · Inference not verified', { exact: true }).waitFor();
  console.log('PASS native Settings creates a keyless provider and displays separate inference status');
  await api('/api/model-config/providers/uat-lab/credential', 'PUT', { revision: 1, credential: { source: 'environment', environment_variable: 'LAB_UAT_MODEL_KEY' } });
  await page.reload();
  await page.getByRole('tab', { name: 'AI Models', exact: true }).click();
  await page.getByRole('button', { name: 'Advanced model configuration', exact: true }).waitFor();
  await page.getByRole('textbox', { name: /Search/ }).fill('UAT Lab');
  await page.getByText(/Environment: LAB_UAT_MODEL_KEY/).waitFor();
  if ((await page.locator('body').innerText()).includes(process.env.LAB_UAT_MODEL_KEY)) throw new Error('Secret leaked into browser');
  console.log('PASS explicit EnvRef shows its name, hides its value, and requires backend restart for rotation');
  const before = await api('/api/model-selection/default');
  if (before.selection.model !== null) throw new Error('Provider edit changed the default model');
  console.log('PASS provider writes preserve default selection ownership');
} finally {
  await browser?.close();
  await app.close();
  await rm(root, { recursive: true, force: true });
}
