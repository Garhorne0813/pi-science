import type { CreateBindingRequest, CreateEndpointRequest, CreateProviderRequest, CredentialMetadata, Endpoint, Model, ModelCapabilities, ModelRead, Provider, ProviderView, ProviderEndpointBinding, UpdateBindingRequest, UpdateEndpointRequest, UpdateProviderRequest } from "@pi-science/contracts";
import type { RuntimeCatalog, RuntimeCatalogService } from "../../runtime/agent/runtime-catalog.js";
import type { SettingsStore } from "../../storage/settings-store.js";
import type { CredentialStore } from "../credential-store.js";
import type { CapabilityPatch } from "../capability-resolver.js";
import type { MigrationResult } from "../migration/migrate-custom-providers.js";
import type { ModelResourceRepository } from "../model-resource-repository.js";
import type { RuntimeModelResolver } from "../runtime-model-resolver.js";
import type { ProviderRead, DiscoveryResult, HealthResult } from "./types.js";

export interface ModelResourceContext {
  readonly repository: ModelResourceRepository;
  readonly credentials: CredentialStore;
  readonly settings: SettingsStore;
  readonly runtimeCatalog?: Pick<RuntimeCatalogService, "getCatalog">;
  ensureMigrated(): Promise<MigrationResult>;
  resolveAvailableModels(): ReturnType<RuntimeModelResolver["resolveAvailableModels"]>;
  resolveModelRoute(ref: string): ReturnType<RuntimeModelResolver["resolveModelRoute"]>;
  isModelAvailable(ref: string): Promise<boolean>;
  listProviders(catalog?: RuntimeCatalog): Promise<ProviderRead[]>;
  providerViews(selectable: Set<string>, inputFormats?: Map<string, string[]>, catalogAvailable?: boolean): Promise<ProviderView[]>;
  getProvider(id: string): Promise<ProviderRead>;
  createProvider(input: CreateProviderRequest): Promise<Provider>;
  upsertLegacyProvider(input: {
    id: string;
    name: string;
    base_url: string;
    api: string;
    models: string[];
    api_key?: string;
    reasoning?: boolean;
    context_window?: number;
    model_hints?: Record<string, { context_window?: number; reasoning?: boolean; thinking_levels?: string[]; source?: string }>;
  }): Promise<{ provider: Provider; endpoint: Endpoint; binding: ProviderEndpointBinding; models: Model[] }>;
  updateProvider(id: string, input: UpdateProviderRequest): Promise<Provider>;
  deleteProvider(id: string, cascade?: boolean): Promise<{ id: string; removed_models: number; removed_bindings: number }>;
  createCustomProvider(input: { name: string; base_url: string; protocol?: Endpoint["protocol"]; api?: Endpoint["api"]; data_egress?: Endpoint["data_egress"]; auth?: { kind: "api_key" | "none"; secret?: string } | null; models?: string[] }): Promise<{ provider: Provider; endpoint: Endpoint; credential: CredentialMetadata | null; binding: ProviderEndpointBinding; discovery?: { model_count: number }; discovery_error?: string }>;
  updateCustomProvider(id: string, input: { name?: string; base_url?: string; api?: Endpoint["api"]; auth?: { kind?: "api_key" | "none"; secret?: string } | null }): Promise<{ provider: Provider; endpoint: Endpoint; binding: ProviderEndpointBinding }>;
  deleteCustomProvider(id: string): Promise<{ id: string; removed_endpoints: number; removed_credentials: number }>;
  testProviderConfiguration(input: { protocol: Endpoint["protocol"]; base_url: string; api?: Endpoint["api"]; auth?: { kind: "api_key" | "none"; secret?: string } | null }): Promise<{ ok: true; health: "ready"; models: Array<{ id: string; display_name: string; kind?: "chat" | "embedding" | "rerank" | "unknown"; capabilities: CapabilityPatch }> }>;
  listEndpoints(): Promise<Endpoint[]>;
  getEndpoint(id: string): Promise<Endpoint>;
  createEndpoint(input: CreateEndpointRequest): Promise<Endpoint>;
  updateEndpoint(id: string, input: UpdateEndpointRequest): Promise<Endpoint>;
  deleteEndpoint(id: string, cascade?: boolean): Promise<{ id: string; removed_bindings: number }>;
  setEndpointEnabled(id: string, enabled: boolean): Promise<Endpoint>;
  probeEndpoint(id: string): Promise<HealthResult>;
  listBindings(filters?: { provider_id?: string; endpoint_id?: string }): Promise<ProviderEndpointBinding[]>;
  createBinding(input: CreateBindingRequest): Promise<ProviderEndpointBinding>;
  updateBinding(id: string, input: UpdateBindingRequest): Promise<ProviderEndpointBinding>;
  deleteBinding(id: string): Promise<{ id: string }>;
  listModels(filters?: { provider_id?: string; available?: boolean }, catalog?: RuntimeCatalog): Promise<ModelRead[]>;
  getModel(providerId: string, modelId: string): Promise<ModelRead>;
  updateModel(providerId: string, modelId: string, body: Record<string, unknown>): Promise<ModelRead>;
  applyRuntimeCapabilities(providerId: string, modelId: string, patch: Partial<ModelCapabilities>): Promise<Model | null>;
  deleteModel(providerId: string, modelId: string): Promise<{ provider_id: string; model_id: string; default_cleared: boolean }>;
  discover(providerId: string, bindingId?: string): Promise<DiscoveryResult>;
  migrationStatus(): Promise<MigrationResult>;
  modelPreferences(): Promise<{ default_model: string | null; thinking: string; compaction_enabled: boolean; compaction_threshold_percent: number }>;
}
